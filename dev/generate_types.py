#!/usr/bin/env python3
"""Generates python_anvil/types from the API specs in schema/.

- types/rest.py: pydantic models for the REST API's request bodies, from
  schema/openapi.json, with datamodel-code-generator.
- types/graphql.py: pydantic models for every type in the GraphQL schema,
  objects, inputs and enums, from schema/anvil_schema.graphql, with
  datamodel-code-generator.
- types/operations.py: a pydantic model of the arguments of every query and
  mutation, e.g. CreateEtchPacketArgs, from the same schema with graphql-core.

Reads the checked-in specs only, so this runs offline. `dev/fetch_schema.py`
(`make update-schema`) is what refreshes them.

Usage: poetry run python dev/generate_types.py
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
from pathlib import Path

from graphql import (
    GraphQLArgument,
    GraphQLEnumType,
    GraphQLInputObjectType,
    GraphQLList,
    GraphQLNamedType,
    GraphQLNonNull,
    GraphQLScalarType,
    GraphQLSchema,
    GraphQLType,
    build_schema,
)

# graphql-core marks an argument without a default with its own Undefined
from graphql.pyutils import Undefined
from pydantic import BaseModel


ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "schema" / "anvil_schema.graphql"
OPENAPI_PATH = ROOT / "schema" / "openapi.json"
TYPES_DIR = ROOT / "python_anvil" / "types"
REST_PATH = TYPES_DIR / "rest.py"
GRAPHQL_PATH = TYPES_DIR / "graphql.py"
OPERATIONS_PATH = TYPES_DIR / "operations.py"

BASE_CLASS = "python_anvil.types._base.GeneratedModel"

# The same for both datamodel-code-generator runs
CODEGEN_OPTIONS = [
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--base-class",
    BASE_CLASS,
    "--target-python-version",
    "3.10",
    "--snake-case-field",
    "--allow-population-by-field-name",
    "--extra-fields",
    "allow",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-annotated",
    "--field-constraints",
    "--use-schema-description",
    "--use-double-quotes",
    "--disable-timestamp",
    # Enums as Literal types, so the fields take and give plain strings
    "--enum-field-as-literal",
    "all",
    # The outputs are formatted with ruff afterwards
    "--formatters",
    "builtin",
]

# The schema's custom scalars, as Python types
GRAPHQL_SCALARS = {
    "String": "str",
    "Int": "int",
    "Float": "float",
    "Boolean": "bool",
    "ID": "str",
    "Date": "str",
    "JSON": "Any",
    "Upload": "Any",
}


def header(source: Path, extra: str = "") -> str:
    return (
        f"# Generated by dev/generate_types.py from {source.relative_to(ROOT)}. Do not edit by hand.\n"
        "# Run `make generate` to regenerate.\n" + extra
    )


def run_codegen(
    input_path: Path, input_type: str, output_path: Path, *extra: str
) -> None:
    subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(input_path),
            "--input-file-type",
            input_type,
            "--output",
            str(output_path),
            *CODEGEN_OPTIONS,
            *extra,
        ],
        check=True,
        cwd=ROOT,
    )


def generate_rest() -> None:
    run_codegen(OPENAPI_PATH, "openapi", REST_PATH, "--collapse-root-models")
    source = REST_PATH.read_text(encoding="utf-8")
    # Plain strings for emails and dates. EmailStr would need the email-validator
    # package, and AwareDatetime would turn a date string into a datetime that
    # the JSON encoder can't send, and reject one with no timezone.
    source = _use_plain_str(source, ["EmailStr", "AwareDatetime"])
    source = re.sub(
        r"^# generated by datamodel-codegen:\n#   filename:  .*\n",
        "",
        source,
        flags=re.M,
    )
    REST_PATH.write_text(header(OPENAPI_PATH) + source, encoding="utf-8")


def _use_plain_str(source: str, type_names: list[str]) -> str:
    """Replace pydantic types with `str`, and drop them from the pydantic import.

    The import may be on one line or wrapped over several, so the names are
    removed from the import first, by whichever form they take, and then
    replaced everywhere else.
    """
    for name in type_names:
        # `from pydantic import A, Name, B` or a wrapped `    Name,` line
        source = re.sub(
            rf"^(from pydantic import [^(\n]*?)\b{name}, ", r"\1", source, flags=re.M
        )
        source = re.sub(
            rf"^(from pydantic import [^(\n]*?), {name}\b", r"\1", source, flags=re.M
        )
        source = re.sub(rf"^\s*{name},\n", "", source, flags=re.M)
        source = re.sub(rf"\b{name}\b", "str", source)
    return source


def generate_graphql() -> None:
    overrides = json.dumps({"JSON": "typing.Any", "Upload": "typing.Any"})
    run_codegen(
        SCHEMA_PATH,
        "graphql",
        GRAPHQL_PATH,
        "--graphql-no-typename",
        "--type-overrides",
        overrides,
    )
    source = GRAPHQL_PATH.read_text(encoding="utf-8")
    source = re.sub(
        r"^# generated by datamodel-codegen:\n#   filename:  .*\n",
        "",
        source,
        flags=re.M,
    )
    GRAPHQL_PATH.write_text(header(SCHEMA_PATH) + source, encoding="utf-8")


def generate_operations(schema: GraphQLSchema) -> None:
    """A model of the arguments of every query and mutation."""
    lines = [
        header(
            SCHEMA_PATH,
            '"""The arguments of every query and mutation in the Anvil GraphQL schema, as pydantic models.\n\n'
            "Field names are snake_case; `model_dump(by_alias=True, exclude_none=True)` gives the\n"
            "camelCase variables to send. Input object and enum types come from `python_anvil.types.graphql`.\n"
            '"""\n',
        ),
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Any",
        "",
        "from pydantic import Field",
        "",
        "from python_anvil.types import graphql",
        "from python_anvil.types._base import GeneratedModel",
        "",
        "",
    ]

    names: dict[str, str] = {}
    all_names: list[str] = []
    for operation, root in (
        ("query", schema.query_type),
        ("mutation", schema.mutation_type),
    ):
        if root is None:
            continue
        for field_name, field in root.fields.items():
            class_name = f"{field_name[0].upper()}{field_name[1:]}Args"
            if class_name in names:
                raise ValueError(f"{class_name} would be both a query and a mutation")
            names[class_name] = field_name
            all_names.append(class_name)

            lines.append(f"class {class_name}(GeneratedModel):")
            description = f"Arguments of the `{field_name}` {operation}."
            if field.description:
                description = f"{description}\n\n{_indent(field.description.strip())}"
            lines.append(f'    """{description}\n    """')
            lines.append("")
            if not field.args:
                lines.append("    pass")
            for arg_name, arg in field.args.items():
                lines.extend(_argument_lines(arg_name, arg))
            lines.extend(["", ""])

    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for name in sorted(all_names))
    lines.append("]")
    lines.append("")
    OPERATIONS_PATH.write_text("\n".join(lines), encoding="utf-8")


def _argument_lines(arg_name: str, arg: GraphQLArgument) -> list[str]:
    required = isinstance(arg.type, GraphQLNonNull) and arg.default_value is Undefined
    annotation = _python_type(arg.type)
    if not required:
        annotation = f"{annotation} | None"

    field_name = _snake_case(arg_name)
    # A Python keyword, or a name pydantic's BaseModel already uses (like `schema`)
    if keyword.iskeyword(field_name) or hasattr(BaseModel, field_name):
        field_name = f"{field_name}_"
    field_options = [f'alias="{arg_name}"'] if field_name != arg_name else []
    descriptions = []
    if arg.description:
        descriptions.append(arg.description.strip())
    if arg.default_value is not Undefined:
        descriptions.append(
            f"Defaults to `{_graphql_literal(arg.default_value)}` when left out."
        )
    if descriptions:
        field_options.append(f"description={json.dumps(' '.join(descriptions))}")

    if field_options:
        annotation = f"Annotated[{annotation}, Field({', '.join(field_options)})]"
    default = "" if required else " = None"
    return [f"    {field_name}: {annotation}{default}"]


def _python_type(graphql_type: GraphQLType) -> str:
    if isinstance(graphql_type, GraphQLNonNull):
        return _python_type(graphql_type.of_type)
    if isinstance(graphql_type, GraphQLList):
        inner = _python_type(graphql_type.of_type)
        if not isinstance(graphql_type.of_type, GraphQLNonNull):
            inner = f"{inner} | None"
        return f"list[{inner}]"
    if isinstance(graphql_type, GraphQLScalarType):
        return GRAPHQL_SCALARS.get(graphql_type.name, "Any")
    if isinstance(graphql_type, (GraphQLEnumType, GraphQLInputObjectType)):
        return f"graphql.{graphql_type.name}"
    if isinstance(graphql_type, GraphQLNamedType):  # pragma: no cover
        return "Any"
    raise TypeError(f"Unexpected GraphQL type {graphql_type!r}")  # pragma: no cover


def _graphql_literal(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    return json.dumps(value)


def _snake_case(name: str) -> str:
    """Convert camelCase to snake_case, keeping acronyms and their plurals whole: mergePDFs -> merge_pdfs."""
    # An acronym followed by a word: "URLFor" -> "URL_For". Two lowercase letters
    # or more make a word, so a plural "s" stays with its acronym.
    name = re.sub(r"([A-Z]+)([A-Z][a-z]{2,})", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def _indent(text: str, spaces: int = 4) -> str:
    return "\n".join(
        f"{' ' * spaces}{line}" if line else "" for line in text.splitlines()
    )


def main() -> None:
    TYPES_DIR.mkdir(exist_ok=True)
    generate_rest()
    generate_graphql()
    generate_operations(build_schema(SCHEMA_PATH.read_text(encoding="utf-8")))

    outputs = [str(REST_PATH), str(GRAPHQL_PATH), str(OPERATIONS_PATH)]
    subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "--quiet", *outputs],
        check=True,
        cwd=ROOT,
    )
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--quiet", *outputs],
        check=True,
        cwd=ROOT,
    )
    for output in outputs:
        print(f"Wrote {Path(output).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
